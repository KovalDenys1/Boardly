import { NextRequest } from 'next/server'
import { logger } from './logger'

/**
 * CSRF Protection utility for Next.js API routes
 * 
 * Verifies that requests come from the same origin to prevent CSRF attacks.
 * This is a simple implementation - for production, consider using a library
 * like 'csrf' or implementing token-based CSRF protection.
 */

const DEFAULT_ALLOWED_ORIGINS = [
  process.env.NEXTAUTH_URL || 'http://localhost:3000',
  'http://localhost:3000',
  'http://127.0.0.1:3000',
  'https://boardly.online',
]

function normalizeOrigin(value: string | null | undefined): string | null {
  if (!value) return null
  try {
    const parsed = new URL(value)
    if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') {
      return null
    }
    return parsed.origin
  } catch {
    return null
  }
}

function resolveAllowedOrigins(request: NextRequest): string[] {
  const configuredOrigins = process.env.ALLOWED_ORIGINS
    ? process.env.ALLOWED_ORIGINS.split(',').map((origin) => origin.trim())
    : DEFAULT_ALLOWED_ORIGINS

  const normalized = configuredOrigins
    .map((origin) => normalizeOrigin(origin))
    .filter((origin): origin is string => origin !== null)

  normalized.push(request.nextUrl.origin)
  return Array.from(new Set(normalized))
}

function extractRequestOrigin(request: NextRequest): string | null {
  const originHeader = request.headers.get('origin')
  const normalizedOriginHeader = normalizeOrigin(originHeader)
  if (normalizedOriginHeader) return normalizedOriginHeader

  const referer = request.headers.get('referer')
  return normalizeOrigin(referer)
}

function isOriginAllowed(requestOrigin: string, allowedOrigin: string): boolean {
  if (allowedOrigin.startsWith('*.')) {
    const domain = allowedOrigin.slice(2)
    try {
      const host = new URL(requestOrigin).hostname
      return host === domain || host.endsWith(`.${domain}`)
    } catch {
      return false
    }
  }

  return requestOrigin === allowedOrigin
}

/**
 * Server-to-server callbacks that authenticate the request body itself (signature
 * verification) rather than the browser origin. They arrive with no Origin and no
 * Referer, so the origin check would reject every delivery — see #713, where this
 * silently blocked every Stripe subscription webhook in production.
 *
 * Only add a path here when the route handler verifies the caller
 * cryptographically. Matching is exact, so a path merely starting with one of
 * these is not exempt.
 */
const SIGNATURE_AUTHENTICATED_WEBHOOK_PATHS = new Set([
  '/api/stripe/webhook',
  '/api/resend/inbound',
])

export function isSignatureAuthenticatedWebhook(pathname: string): boolean {
  return SIGNATURE_AUTHENTICATED_WEBHOOK_PATHS.has(pathname)
}

/**
 * Endpoints the *browser's own reporting machinery* posts to, not page script — a CSP
 * violation report (#1145) is generated by the engine when it blocks or would block a
 * script, and delivered with no Origin/Referer guaranteed across browsers and no way for
 * a page to attach our CSRF proof to it (it isn't a `fetch()` call this app makes). Safe
 * to exempt because the route does nothing an attacker could want a forged POST to do -
 * it only logs and stores telemetry, never anything scoped to a session or an account -
 * and it is rate-limited and body-size-capped in its own handler instead.
 *
 * Same exact-match discipline as the webhook set above: a path merely starting with one
 * of these is not exempt.
 */
const UNAUTHENTICATED_REPORTING_PATHS = new Set([
  '/api/security/csp-report',
])

export function isUnauthenticatedReportingEndpoint(pathname: string): boolean {
  return UNAUTHENTICATED_REPORTING_PATHS.has(pathname)
}

/**
 * Routes whose own signed token authenticates the request, so the browser-origin check
 * this file otherwise enforces adds nothing and would only break a legitimate caller.
 *
 * `/api/notifications/unsubscribe` (#1154) is the RFC 8058 one-click unsubscribe target:
 * a mail client delivers `List-Unsubscribe-Post` as a server-to-server POST with no
 * Origin or Referer a page could attach — the same shape as the CSP report exemption
 * above, but authenticated (verifyNotificationUnsubscribeToken) rather than open, since
 * this one mutates a user's preferences. Without this exemption every provider's
 * one-click "Unsubscribe" would get a silent 403 the person never sees.
 *
 * Same exact-match discipline as the sets above: a path merely starting with one of
 * these is not exempt.
 */
const TOKEN_AUTHENTICATED_PATHS = new Set([
  '/api/notifications/unsubscribe',
])

export function isTokenAuthenticatedEndpoint(pathname: string): boolean {
  return TOKEN_AUTHENTICATED_PATHS.has(pathname)
}

/**
 * Verify that the request origin matches our allowed origins
 */
export function verifyCsrfToken(request: NextRequest): boolean {
  // Skip CSRF check for GET, HEAD, OPTIONS requests (safe methods)
  const method = request.method.toUpperCase()
  if (['GET', 'HEAD', 'OPTIONS'].includes(method)) {
    return true
  }

  const requestOrigin = extractRequestOrigin(request)

  // In development, allow localhost and local hostnames
  if (process.env.NODE_ENV === 'development' && requestOrigin) {
    if (requestOrigin.includes('localhost') || requestOrigin.includes('127.0.0.1')) {
      return true
    }
  }

  if (!requestOrigin) {
    // In development, allow requests without origin (e.g., same-origin)
    if (process.env.NODE_ENV === 'development') {
      return true
    }
    logger?.warn('CSRF check failed: No origin or referer header')
    return false
  }

  // Check if origin is in allowed list
  const allowedOrigins = resolveAllowedOrigins(request)
  const isAllowed = allowedOrigins.some((allowedOrigin) =>
    isOriginAllowed(requestOrigin, allowedOrigin)
  )

  if (!isAllowed) {
    logger?.warn(`CSRF check failed: Origin ${requestOrigin} not in allowed list`)
  }

  return isAllowed
}

/**
 * Set security headers to prevent CSRF and other attacks
 */
export function getSecurityHeaders() {
  return {
    // Prevent MIME type sniffing
    'X-Content-Type-Options': 'nosniff',
    
    // Enable XSS filtering
    'X-XSS-Protection': '1; mode=block',
    
    // Prevent clickjacking
    'X-Frame-Options': 'SAMEORIGIN',
    
    // Referrer policy
    'Referrer-Policy': 'strict-origin-when-cross-origin',
    
    // Permissions policy (formerly Feature-Policy)
    'Permissions-Policy': 'geolocation=(), microphone=(), camera=()',
  }
}
